"""Shared contract: the ONLY data model the three agents exchange.

Pydantic v2. Red line (enforced by validators): every Decision / Risk /
ActionItem must carry segment_ids pointing at real transcript segments.
Items without evidence are dropped by the agents (see analyst/extractor).
"""
from __future__ import annotations

import re
from datetime import datetime
from typing import Optional

from pydantic import BaseModel, Field, field_validator

# Meeting ids travel inside URL paths (/meetings/{id}/...) and file
# names (audio uploads), so their charset is deliberately boring:
# letters, digits, '.', '_' and '-'. Anything else (spaces, '/', '?',
# '#', ...) makes a meeting unaddressable from the web UI / HTTP
# routes, so it is rejected at the model boundary — every creation
# path (REST create, JSON import, propose-by-JSON) validates here.
MEETING_ID_PATTERN = re.compile(r"^[A-Za-z0-9._-]+$")


class Participant(BaseModel):
    user_id: str
    name: str
    email: Optional[str] = None
    role: Optional[str] = None  # organizer / attendee


class TranscriptSegment(BaseModel):
    id: int
    speaker: str
    start_sec: float = 0.0
    end_sec: float = 0.0
    text: str


class Decision(BaseModel):
    text: str
    decided_by: Optional[str] = None
    segment_ids: list[int]

    @field_validator("segment_ids")
    @classmethod
    def _need_evidence(cls, v: list[int]) -> list[int]:
        if not v:
            raise ValueError("Decision without segment_ids evidence is forbidden")
        return v


class Topic(BaseModel):
    title: str
    segment_ids: list[int] = Field(default_factory=list)
    summary: str = ""


class Risk(BaseModel):
    text: str
    segment_ids: list[int]
    severity: str = "medium"  # low / medium / high

    @field_validator("segment_ids")
    @classmethod
    def _need_evidence(cls, v: list[int]) -> list[int]:
        if not v:
            raise ValueError("Risk without segment_ids evidence is forbidden")
        return v


class MinutesResult(BaseModel):
    summary: str = ""
    executive_summary: str = ""
    detailed_minutes: str = ""
    topics: list[Topic] = Field(default_factory=list)
    decisions: list[Decision] = Field(default_factory=list)
    risks: list[Risk] = Field(default_factory=list)
    open_questions: list[str] = Field(default_factory=list)
    # Provenance: which path produced these minutes.
    # llm | llm_repaired | rule_fallback | rules
    generation_source: Optional[str] = None
    generation_model: Optional[str] = None
    # Non-fatal quality notes a human should see (e.g. decisions that
    # still look like assignments after the repair retry — kept
    # verbatim, never silently stripped; see minutes/analyst.py).
    generation_notes: list[str] = Field(default_factory=list)


class BriefResult(BaseModel):
    """Pre-meeting brief generated by CalendarAgent.prepare_brief and
    stored on the Meeting (Meeting.brief). Regeneration overwrites the
    previous brief and refreshes generated_at."""

    content: str = ""  # markdown
    generated_at: Optional[datetime] = None
    # History meetings whose decisions / open tasks fed into this brief.
    source_meeting_ids: list[str] = Field(default_factory=list)


class MeetingEvent(BaseModel):
    """One entry of the meeting's event-bus audit log (see
    src/orchestrator/eventbus.py). Every key pipeline event is appended
    here by EventBus.emit() and persisted with the meeting (Postgres
    JSONB included). Payloads are SUMMARIES only — counts, ids, short
    status strings; never transcript text, never credentials."""

    type: str
    at: Optional[datetime] = None
    payload: dict = Field(default_factory=dict)


class Rejection(BaseModel):
    """One human rejection at a confirmation gate (see orchestrator/gates.py
    and the /reject-minutes / /reject-tasks endpoints). Kept as an audit
    trail on the Meeting; rejecting never deletes the generated content."""

    gate: str  # minutes | tasks
    reason: str = ""
    at: Optional[datetime] = None


class ActionItem(BaseModel):
    id: str
    title: str
    owner_id: Optional[str] = None
    owner_raw: str = ""
    owner_confidence: float = 0.0  # <0.7 forces human assignment
    # auto (Assigner resolved it) | manual (a human patched it via
    # PATCH /meetings/{id}/tasks/{item_id}); dispatch uses the final value.
    assignment_source: Optional[str] = None
    due_date: Optional[str] = None  # ISO date YYYY-MM-DD
    due_raw: Optional[str] = None
    priority: str = "P2"  # P0 / P1 / P2
    source_segment_ids: list[int]
    external_system: Optional[str] = None
    external_task_id: Optional[str] = None
    # Set when dispatch to an external task system failed for THIS item
    # (status becomes "dispatch_failed"); other items still dispatch.
    dispatch_error: Optional[str] = None
    status: str = "pending_confirmation"
    idempotency_key: Optional[str] = None
    # Reminder bookkeeping (orchestrator/reminders.py): set when the
    # due-soon / overdue notification for this item has been sent, which
    # is what makes repeated reminder scans idempotent.
    reminder_sent_at: Optional[datetime] = None
    overdue_notified_at: Optional[datetime] = None
    # Provenance: which path extracted this item.
    # llm | llm_repaired | rule_fallback | rules
    generation_source: Optional[str] = None

    @field_validator("source_segment_ids")
    @classmethod
    def _need_evidence(cls, v: list[int]) -> list[int]:
        if not v:
            raise ValueError("ActionItem without source_segment_ids is forbidden")
        return v


class Meeting(BaseModel):
    id: str
    title: str

    @field_validator("id")
    @classmethod
    def _id_charset(cls, v: str) -> str:
        if not MEETING_ID_PATTERN.match(v or ""):
            raise ValueError(
                "meeting id may only contain ASCII letters, digits, "
                "'.', '_' and '-' (it is used in URL paths and file "
                f"names); got {v!r}")
        return v

    calendar_event_id: Optional[str] = None
    start_at: Optional[datetime] = None
    timezone: str = "Asia/Shanghai"
    participants: list[Participant] = Field(default_factory=list)
    audio_url: Optional[str] = None
    # Cloud ASR task id (volcano engine): written the moment the task is
    # submitted, BEFORE polling finishes, so a crashed process can still
    # look the result up by id instead of losing the task.
    asr_task_id: Optional[str] = None
    transcript: list[TranscriptSegment] = Field(default_factory=list)
    summary: Optional[str] = None
    executive_summary: Optional[str] = None
    detailed_minutes: Optional[str] = None
    topics: list[Topic] = Field(default_factory=list)
    decisions: list[Decision] = Field(default_factory=list)
    risks: list[Risk] = Field(default_factory=list)
    open_questions: list[str] = Field(default_factory=list)
    minutes: Optional[MinutesResult] = None
    generation_source: Optional[str] = None
    generation_model: Optional[str] = None
    tasks_generation_source: Optional[str] = None
    tasks_generation_model: Optional[str] = None
    action_items: list[ActionItem] = Field(default_factory=list)
    follow_up_candidate_times: list[str] = Field(default_factory=list)
    minutes_confirmed: bool = False
    tasks_confirmed: bool = False
    # Pre-meeting brief (POST /meetings/{id}/brief); None until generated.
    brief: Optional[BriefResult] = None
    # Audit trail of gate rejections (reject-minutes / reject-tasks).
    rejections: list[Rejection] = Field(default_factory=list)
    # Event-bus audit log (src/orchestrator/eventbus.py): every key
    # pipeline event for this meeting, in publish order. Appended by
    # EventBus.emit(); persisted with the meeting like everything else.
    events: list[MeetingEvent] = Field(default_factory=list)
    # Confirmation-gate timeout bookkeeping (orchestrator/gate_timeouts.py):
    # when the flow entered each awaiting_* state. The timeout scanner
    # measures the wait from here. Re-entering a gate (re-run after a
    # minutes rejection, re-extract after a tasks rejection) overwrites
    # the stamp and clears the matching *_timeout_notified_at marker.
    # None on meetings created before this field existed — the scanner
    # backfills None with the first-scan time, never backdates, so a
    # legacy meeting can never time out on first sight.
    minutes_gate_entered_at: Optional[datetime] = None
    tasks_gate_entered_at: Optional[datetime] = None
    # Escalation-notice stamps for the CURRENT gate entry: set when the
    # timeout scanner has sent its (single) escalation for this entry,
    # which is what makes the notify action exactly-once per entry —
    # same stamp pattern as ActionItem.reminder_sent_at.
    minutes_gate_timeout_notified_at: Optional[datetime] = None
    tasks_gate_timeout_notified_at: Optional[datetime] = None
    # Non-fatal problems a human should see (empty transcript, calendar
    # dispatch failure, ...). Agents append here instead of failing silently.
    warnings: list[str] = Field(default_factory=list)
    status: str = "scheduled"

    def valid_segment_ids(self) -> set[int]:
        return {s.id for s in self.transcript}

    def base_date(self):
        if self.start_at:
            return self.start_at.date()
        from datetime import date

        return date.today()
